                                         // Topic: if-else if
let num = 3;

if(num == 1){
    console.log("a");
}
else if(num == 2){
    console.log("b");
}
else if(num == 3){
    console.log("c");
}
else{
    console.log("none");
}

                                          // Topic: Switch case
let num = 3;

switch(num){
    case 1:console.log("a");
    break;
    case 2:console.log("b");
    break;
    case 3:console.log("c");
    break;
    case 4:console.log("d");
    break;
    default:console.log("none");
    
}
